package main

import (
	"fmt"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"

	vtextpb "github.com/planetscale/vtprotobuf/vtproto"
	vtpoolext "github.com/thanos-io/thanos/pkg/vtproto/gen/vtpoolext"
)

const (
	contextPackage = protogen.GoImportPath("context")
	grpcPackage    = protogen.GoImportPath("google.golang.org/grpc")
	syncPackage    = protogen.GoImportPath("sync")
	vtprotoPackage = protogen.GoImportPath("github.com/thanos-io/thanos/pkg/vtproto")
)

// hasMempool reports whether the message has option (vtproto.mempool) = true.
func hasMempool(msg *protogen.Message) bool {
	opts, ok := msg.Desc.Options().(*descriptorpb.MessageOptions)
	if !ok || opts == nil {
		return false
	}
	if !proto.HasExtension(opts, vtextpb.E_Mempool) {
		return false
	}
	switch v := proto.GetExtension(opts, vtextpb.E_Mempool).(type) {
	case bool:
		return v
	case *bool:
		return v != nil && *v
	default:
		return false
	}
}

// resolvePoolMode returns the pool return mode for a message, or "" if the
// message has no explicit vtpool.pool_return option set. Only messages with
// an explicit option will have pool-aware handlers generated.
func resolvePoolMode(msg *protogen.Message) string {
	opts, ok := msg.Desc.Options().(*descriptorpb.MessageOptions)
	if !ok || opts == nil {
		return ""
	}
	if !proto.HasExtension(opts, vtpoolext.E_PoolReturn) {
		return ""
	}
	switch v := proto.GetExtension(opts, vtpoolext.E_PoolReturn).(type) {
	case vtpoolext.PoolReturnMode:
		return poolModeString(v)
	case *vtpoolext.PoolReturnMode:
		if v == nil {
			return ""
		}
		return poolModeString(*v)
	default:
		return ""
	}
}

func poolModeString(v vtpoolext.PoolReturnMode) string {
	switch v {
	case vtpoolext.PoolReturnMode_POOL_RETURN_DEFER:
		return "defer"
	case vtpoolext.PoolReturnMode_POOL_RETURN_CALLER:
		return "caller"
	case vtpoolext.PoolReturnMode_POOL_RETURN_REFCOUNT:
		return "refcount"
	default:
		return ""
	}
}

// poolMethod holds info about a service method whose input message is poolable.
type poolMethod struct {
	service  *protogen.Service
	method   *protogen.Method
	stream   bool   // true for server-streaming (RecvMsg pattern)
	poolMode string // resolved pool return mode for this method's input
}

// generateFile produces a _grpc_vtpool.pb.go file for proto files that have
// services with poolable input messages.
func generateFile(gen *protogen.Plugin, file *protogen.File) {
	if len(file.Services) == 0 {
		return
	}

	var methods []poolMethod
	for _, svc := range file.Services {
		for _, m := range svc.Methods {
			if !hasMempool(m.Input) {
				continue
			}
			mode := resolvePoolMode(m.Input)
			if mode == "" {
				continue
			}
			if m.Desc.IsStreamingClient() {
				continue
			}
			methods = append(methods, poolMethod{
				service:  svc,
				method:   m,
				stream:   m.Desc.IsStreamingServer(),
				poolMode: mode,
			})
		}
	}

	if len(methods) == 0 {
		return
	}

	filename := file.GeneratedFilenamePrefix + "_grpc_vtpool.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-go-grpc-vtpool. DO NOT EDIT.")
	g.P("// versions:")
	g.P("// - protoc-gen-go-grpc-vtpool v", version)
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	genInit(g, methods)

	for _, pm := range methods {
		if pm.stream {
			genStreamHandler(g, pm)
		} else {
			genUnaryHandler(g, pm)
		}
	}
}

// genInit generates an init() that patches each ServiceDesc to use the
// pool-aware handler functions.
func genInit(g *protogen.GeneratedFile, methods []poolMethod) {
	// Group methods by service so we patch each ServiceDesc once.
	type patchEntry struct {
		methodName  string
		handlerName string
		stream      bool
	}
	byService := make(map[string][]patchEntry)
	var serviceOrder []string
	for _, pm := range methods {
		key := pm.service.GoName
		if _, seen := byService[key]; !seen {
			serviceOrder = append(serviceOrder, key)
		}
		byService[key] = append(byService[key], patchEntry{
			methodName:  string(pm.method.Desc.Name()),
			handlerName: vtPoolHandlerName(pm.service, pm.method),
			stream:      pm.stream,
		})
	}

	g.P("func init() {")
	for _, svcName := range serviceOrder {
		entries := byService[svcName]
		descVar := svcName + "_ServiceDesc"

		// Patch unary methods.
		var unary []patchEntry
		for _, e := range entries {
			if !e.stream {
				unary = append(unary, e)
			}
		}
		if len(unary) > 0 {
			g.P("for i, m := range ", descVar, ".Methods {")
			g.P("switch m.MethodName {")
			for _, e := range unary {
				g.P(`case "`, e.methodName, `":`)
				g.P(descVar, ".Methods[i].Handler = ", e.handlerName)
			}
			g.P("}")
			g.P("}")
		}

		// Patch streaming methods.
		var streams []patchEntry
		for _, e := range entries {
			if e.stream {
				streams = append(streams, e)
			}
		}
		if len(streams) > 0 {
			g.P("for i, s := range ", descVar, ".Streams {")
			g.P("switch s.StreamName {")
			for _, e := range streams {
				g.P(`case "`, e.methodName, `":`)
				g.P(descVar, ".Streams[i].Handler = ", e.handlerName)
			}
			g.P("}")
			g.P("}")
		}
	}
	g.P("}")
	g.P()
}

// genUnaryHandler generates a pool-aware unary server handler.
//
// Standard pattern (from protoc-gen-go-grpc):
//
//	func _Svc_Method_Handler(srv interface{}, ctx context.Context,
//	    dec func(interface{}) error, interceptor grpc.UnaryServerInterceptor) (interface{}, error) {
//	    in := new(InputType)
//	    if err := dec(in); err != nil { return nil, err }
//	    ...
//	}
//
// Pool-aware replacement:
//
//	in := InputTypeFromVTPool()
//	defer in.ReturnToVTPool()  // when pool_return=POOL_RETURN_DEFER
func genUnaryHandler(g *protogen.GeneratedFile, pm poolMethod) {
	svc := pm.service
	method := pm.method
	handlerName := vtPoolHandlerName(svc, method)
	inputIdent := method.Input.GoIdent
	fmSymbol := fmt.Sprintf("%s_%s_FullMethodName", svc.GoName, method.GoName)
	fromPool := fromVTPoolIdent(inputIdent)

	g.P("func ", handlerName, "(srv interface{}, ctx ", contextPackage.Ident("Context"),
		", dec func(interface{}) error, interceptor ", grpcPackage.Ident("UnaryServerInterceptor"),
		") (interface{}, error) {")

	g.P("in := ", fromPool, "()")

	switch pm.poolMode {
	case "defer":
		g.P("defer in.ReturnToVTPool()")
	case "refcount":
		g.P("wg := &", syncPackage.Ident("WaitGroup"), "{}")
		g.P("wg.Add(1)")
		g.P("go func() {")
		g.P("wg.Wait()")
		g.P("in.ReturnToVTPool()")
		g.P("}()")
		g.P("defer wg.Done()")
		g.P("ctx = ", vtprotoPackage.Ident("WithReturnWG"), "(ctx, wg)")
	}

	g.P("if err := dec(in); err != nil {")
	if pm.poolMode == "caller" {
		g.P("in.ReturnToVTPool()")
	}
	g.P("return nil, err")
	g.P("}")

	g.P("if interceptor == nil {")
	g.P("return srv.(", svc.GoName, "Server).", method.GoName, "(ctx, in)")
	g.P("}")

	g.P("info := &", grpcPackage.Ident("UnaryServerInfo"), "{")
	g.P("Server: srv,")
	g.P("FullMethod: ", fmSymbol, ",")
	g.P("}")

	g.P("handler := func(ctx ", contextPackage.Ident("Context"), ", req interface{}) (interface{}, error) {")
	g.P("return srv.(", svc.GoName, "Server).", method.GoName, "(ctx, req.(*", inputIdent, "))")
	g.P("}")

	g.P("return interceptor(ctx, in, info, handler)")
	g.P("}")
	g.P()
}

// genStreamHandler generates a pool-aware server-streaming handler.
//
// Standard pattern:
//
//	func _Svc_Method_Handler(srv interface{}, stream grpc.ServerStream) error {
//	    m := new(InputType)
//	    if err := stream.RecvMsg(m); err != nil { return err }
//	    return srv.(SvcServer).Method(m, &grpc.GenericServerStream[In, Out]{ServerStream: stream})
//	}
func genStreamHandler(g *protogen.GeneratedFile, pm poolMethod) {
	svc := pm.service
	method := pm.method
	handlerName := vtPoolHandlerName(svc, method)
	inputIdent := method.Input.GoIdent
	outputIdent := method.Output.GoIdent
	fromPool := fromVTPoolIdent(inputIdent)

	typeParam := g.QualifiedGoIdent(inputIdent) + ", " + g.QualifiedGoIdent(outputIdent)
	streamImpl := g.QualifiedGoIdent(grpcPackage.Ident("GenericServerStream")) + "[" + typeParam + "]"

	g.P("func ", handlerName, "(srv interface{}, stream ", grpcPackage.Ident("ServerStream"), ") error {")

	g.P("m := ", fromPool, "()")
	if pm.poolMode == "defer" {
		g.P("defer m.ReturnToVTPool()")
	}

	g.P("if err := stream.RecvMsg(m); err != nil {")
	if pm.poolMode == "caller" {
		g.P("m.ReturnToVTPool()")
	}
	g.P("return err")
	g.P("}")

	g.P("return srv.(", svc.GoName, "Server).", method.GoName, "(m, &", streamImpl, "{ServerStream: stream})")
	g.P("}")
	g.P()
}

// vtPoolHandlerName returns the name of the pool-aware handler function.
func vtPoolHandlerName(svc *protogen.Service, method *protogen.Method) string {
	return fmt.Sprintf("_%s_%s_VTPoolHandler", svc.GoName, method.GoName)
}

// fromVTPoolIdent returns a protogen.GoIdent for the TypeFromVTPool() function.
// The pool function lives in the same package as the message type.
func fromVTPoolIdent(msgIdent protogen.GoIdent) protogen.GoIdent {
	return protogen.GoIdent{
		GoName:       msgIdent.GoName + "FromVTPool",
		GoImportPath: msgIdent.GoImportPath,
	}
}
